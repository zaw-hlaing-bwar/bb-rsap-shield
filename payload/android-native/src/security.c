static void rasp_scan_task_threads(const char *task_directory,
                                   RaspSecurityReport *report) {
  DIR *directory;
  struct dirent *entry;
  uint32_t entries_read = 0U;

  directory = opendir(task_directory);
  if (directory == NULL) {
    return;
  }

  while (entries_read < RASP_SECURITY_MAX_DIRECTORY_ENTRIES &&
         (entry = readdir(directory)) != NULL) {
    char path[PATH_MAX];
    char thread_name[128];
    char path_format[RASP_DECODED_LONG_STRING_SIZE];
    FILE *file;

    entries_read++;

    if (entry->d_name[0] == '.') {
      continue;
    }

    if (!rasp_decode_report_string(RASP_REPORT_STRING_FORMAT_TASK_COMM,
                                   path_format, sizeof(path_format)) ||
        snprintf(path, sizeof(path), path_format, task_directory,
                 entry->d_name) >= (int)sizeof(path)) {
      continue;
    }

    file = fopen(path, "r");
    if (file == NULL) {
      continue;
    }

    if (fgets(thread_name, sizeof(thread_name), file) != NULL) {
      rasp_trim_newline(thread_name);
      rasp_scan_thread_name_value(thread_name, report);
    }

    (void)fclose(file);
  }

  (void)closedir(directory);
}

