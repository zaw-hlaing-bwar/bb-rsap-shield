static void rasp_property_evidence(char *buffer, size_t buffer_size,
                                   const char *name, const char *value) {
  char format[RASP_DECODED_LONG_STRING_SIZE];

  if (buffer == NULL || buffer_size == 0U) {
    return;
  }
  if (!rasp_decode_report_string(RASP_REPORT_STRING_FORMAT_PROPERTY_EVIDENCE,
                                 format, sizeof(format))) {
    buffer[0] = '\0';
    return;
  }
  (void)snprintf(buffer, buffer_size, format, name == NULL ? "" : name,
                 value == NULL ? "" : value);
}

static void rasp_scan_root_property_pair(const char *name, const char *value,
                                         RaspSecurityReport *report,
                                         uint8_t weight) {
  static const RaspReportStringId bad_verified_boot_states[] = {
      RASP_REPORT_STRING_PROBE_VALUE_ORANGE,
      RASP_REPORT_STRING_PROBE_VALUE_RED,
  };
  char evidence[RASP_SECURITY_SIGNAL_EVIDENCE_SIZE];

  if (name == NULL || value == NULL || value[0] == '\0') {
    return;
  }
  rasp_property_evidence(evidence, sizeof(evidence), name, value);

  if (rasp_value_equals_report_string(name,
                                      RASP_REPORT_STRING_PROBE_PROP_RO_BUILD_TAGS) &&
      rasp_value_contains_report_string(value,
                                        RASP_REPORT_STRING_PROBE_VALUE_TEST_KEYS)) {
    rasp_report_add_encoded_signal(
        report, RASP_REPORT_STRING_SIGNAL_ROOT_TEST_KEYS,
        RASP_REPORT_STRING_CATEGORY_ROOT, 75U, 65U, weight, evidence);
  }
  if (rasp_value_equals_report_string(name,
                                      RASP_REPORT_STRING_PROBE_PROP_RO_DEBUGGABLE) &&
      rasp_value_equals_single_char(value, '1')) {
    rasp_report_add_encoded_signal(
        report, RASP_REPORT_STRING_SIGNAL_ROOT_DEBUGGABLE_BUILD,
        RASP_REPORT_STRING_CATEGORY_ROOT, 70U, 60U, weight, evidence);
  }
  if (rasp_value_equals_report_string(name,
                                      RASP_REPORT_STRING_PROBE_PROP_RO_SECURE) &&
      rasp_value_equals_single_char(value, '0')) {
    rasp_report_add_encoded_signal(
        report, RASP_REPORT_STRING_SIGNAL_ROOT_INSECURE_SYSTEM_PROPERTY,
        RASP_REPORT_STRING_CATEGORY_ROOT, 80U, 75U, weight, evidence);
  }
  if (rasp_value_equals_report_string(name,
                                      RASP_REPORT_STRING_PROBE_PROP_SERVICE_ADB_ROOT) &&
      rasp_value_equals_single_char(value, '1')) {
    rasp_report_add_encoded_signal(
        report, RASP_REPORT_STRING_SIGNAL_ROOT_ADB_ROOT,
        RASP_REPORT_STRING_CATEGORY_ROOT, 80U, 75U, weight, evidence);
  }
  if (rasp_value_equals_report_string(
          name, RASP_REPORT_STRING_PROBE_PROP_RO_BOOT_VERIFIEDBOOTSTATE) &&
      rasp_value_equals_any_report_string(
          value, bad_verified_boot_states,
          sizeof(bad_verified_boot_states) / sizeof(bad_verified_boot_states[0]))) {
    rasp_report_add_encoded_signal(
        report, RASP_REPORT_STRING_SIGNAL_ROOT_VERIFIED_BOOT_UNTRUSTED,
        RASP_REPORT_STRING_CATEGORY_ROOT, 75U, 70U, weight, evidence);
  }
  if (rasp_value_equals_report_string(
          name, RASP_REPORT_STRING_PROBE_PROP_RO_BOOT_FLASH_LOCKED) &&
      rasp_value_equals_single_char(value, '0')) {
    rasp_report_add_encoded_signal(
        report, RASP_REPORT_STRING_SIGNAL_ROOT_BOOTLOADER_UNLOCKED,
        RASP_REPORT_STRING_CATEGORY_ROOT, 65U, 55U, weight, evidence);
  }
  if (rasp_value_equals_report_string(
          name, RASP_REPORT_STRING_PROBE_PROP_RO_BOOT_VBMETA_DEVICE_STATE) &&
      rasp_value_equals_report_string(value,
                                      RASP_REPORT_STRING_PROBE_VALUE_UNLOCKED)) {
    rasp_report_add_encoded_signal(
        report, RASP_REPORT_STRING_SIGNAL_ROOT_BOOTLOADER_UNLOCKED,
        RASP_REPORT_STRING_CATEGORY_ROOT, 65U, 55U, weight, evidence);
  }
}

static int rasp_android_property_get(const char *name, char *value,
                                     size_t value_size) {
#if RASP_SECURITY_HAS_ANDROID_PROPERTIES
  int length;
  if (name == NULL || value == NULL || value_size == 0U) {
    return 0;
  }
  value[0] = '\0';
  length = __system_property_get(name, value);
  if (length <= 0) {
    value[0] = '\0';
    return 0;
  }
  value[value_size - 1U] = '\0';
  return 1;
#else
  (void)name;
  (void)value;
  (void)value_size;
  return 0;
#endif
}

static void rasp_scan_android_properties(
    const RaspReportStringId *names, size_t name_count,
    void (*scan_pair)(const char *, const char *, RaspSecurityReport *, uint8_t),
    RaspSecurityReport *report, uint8_t weight) {
  for (size_t index = 0U; index < name_count; index++) {
    char name_buffer[RASP_DECODED_LONG_STRING_SIZE];
    char value[128];
    if (!rasp_decode_report_string(names[index], name_buffer,
                                   sizeof(name_buffer))) {
      continue;
    }
    if (rasp_android_property_get(name_buffer, value, sizeof(value))) {
      scan_pair(name_buffer, value, report, weight);
    }
  }
}

static int rasp_mount_point_is_system_partition(const char *mount_point) {
  return rasp_value_equals_report_string(mount_point,
                                         RASP_REPORT_STRING_PROBE_MOUNT_SYSTEM) ||
         rasp_value_equals_report_string(mount_point,
                                         RASP_REPORT_STRING_PROBE_MOUNT_VENDOR) ||
         rasp_value_equals_report_string(mount_point,
                                         RASP_REPORT_STRING_PROBE_MOUNT_PRODUCT) ||
         rasp_value_equals_report_string(mount_point,
                                         RASP_REPORT_STRING_PROBE_MOUNT_SYSTEM_EXT) ||
         rasp_value_equals_report_string(mount_point,
                                         RASP_REPORT_STRING_PROBE_MOUNT_ODM);
}

static int rasp_mount_options_include_rw(const char *options) {
  const char *token;

  if (options == NULL) {
    return 0;
  }
  token = options;
  while (*token != '\0') {
    if (token[0] == 'r' && token[1] == 'w' &&
        (token[2] == '\0' || token[2] == ',')) {
      return 1;
    }
    token = strchr(token, ',');
    if (token == NULL) {
      return 0;
    }
    token++;
  }
  return 0;
}

static void rasp_scan_root_mounts_line(const char *line,
                                       RaspSecurityReport *report,
                                       uint8_t weight) {
  char device[128];
  char mount_point[128];
  char filesystem[64];
  char options[256];
  char format[RASP_DECODED_LONG_STRING_SIZE];

  if (line == NULL || report == NULL) {
    return;
  }
  if (!rasp_decode_report_string(RASP_REPORT_STRING_FORMAT_MOUNTS_LINE, format,
                                 sizeof(format)) ||
      sscanf(line, format, device, mount_point, filesystem, options) != 4) {
    return;
  }
  if (rasp_mount_point_is_system_partition(mount_point) &&
      rasp_mount_options_include_rw(options)) {
    rasp_report_add_encoded_signal(
        report, RASP_REPORT_STRING_SIGNAL_ROOT_WRITABLE_SYSTEM_PARTITION,
        RASP_REPORT_STRING_CATEGORY_ROOT, 70U, 65U, weight, mount_point);
  }
}

