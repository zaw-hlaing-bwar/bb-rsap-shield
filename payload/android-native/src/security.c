static void rasp_scan_environment_path(const char *path,
                                       RaspSecurityReport *report) {
  char buffer[RASP_SECURITY_MAX_ENVIRON_BYTES];
  FILE *file = fopen(path, "rb");
  size_t bytes_read;
  const char *token;
  char token_buffer[RASP_DECODED_TOKEN_SIZE];

  if (file == NULL) {
    return;
  }

  bytes_read = fread(buffer, 1U, sizeof(buffer) - 1U, file);
  (void)fclose(file);
  buffer[bytes_read] = '\0';
  for (size_t index = 0U; index < bytes_read; index++) {
    if (buffer[index] == '\0') {
      buffer[index] = '\n';
    }
  }

  token = rasp_first_matching_encoded_token(
      buffer, k_environment_tokens, RASP_ARRAY_COUNT(k_environment_tokens),
      token_buffer, sizeof(token_buffer));
  if (token != NULL) {
    rasp_report_add_encoded_signal(
        report, RASP_REPORT_STRING_SIGNAL_INSTRUMENTATION_SUSPICIOUS_ENVIRONMENT,
        RASP_REPORT_STRING_CATEGORY_INSTRUMENTATION, 65U, 50U, 25U, token);
  }
}

static uint8_t rasp_configured_signal_weight(uint8_t configured_weight,
                                             uint8_t fallback_weight) {
  return configured_weight <= 100U ? configured_weight : fallback_weight;
}

static uint8_t rasp_cap_signal_weight(uint8_t signal_weight,
                                      uint8_t configured_weight) {
  if (configured_weight > 100U) {
    return signal_weight;
  }
  return signal_weight < configured_weight ? signal_weight : configured_weight;
}

static int rasp_signal_id_equals(const RaspSecuritySignal *signal,
                                 const char *id) {
  return signal != NULL && id != NULL &&
         strncmp(signal->id, id, RASP_SECURITY_SIGNAL_ID_SIZE) == 0;
}

static int rasp_signal_category_equals(const RaspSecuritySignal *signal,
                                       const char *category) {
  return signal != NULL && category != NULL &&
         strncmp(signal->category, category,
                 RASP_SECURITY_SIGNAL_CATEGORY_SIZE) == 0;
}

static void rasp_recalculate_risk_score(RaspSecurityReport *report) {
  uint32_t risk_score = 0U;

  if (report == NULL) {
    return;
  }

  for (uint32_t index = 0U; index < report->signal_count; index++) {
    risk_score += report->signals[index].weight;
    if (risk_score > 100U) {
      risk_score = 100U;
      break;
    }
  }

  report->risk_score = risk_score;
}

static int rasp_apply_runtime_detector_policy_to_signal(
    RaspSecuritySignal *signal, const RaspSecurityPolicy *policy) {
  if (signal == NULL || policy == NULL) {
    return 0;
  }

  if (rasp_signal_category_equals_encoded(signal,
                                          RASP_REPORT_STRING_CATEGORY_DEBUGGER)) {
    if (policy->debugger_detection_enabled == 0U) {
      return 0;
    }
    signal->weight = rasp_cap_signal_weight(
        signal->weight, policy->debugger_detection_weight);
    return 1;
  }

  if (rasp_signal_category_equals_encoded(
          signal, RASP_REPORT_STRING_CATEGORY_INSTRUMENTATION)) {
    if (policy->instrumentation_detection_enabled == 0U) {
      return 0;
    }
    signal->weight = rasp_cap_signal_weight(
        signal->weight, policy->instrumentation_detection_weight);
    return 1;
  }

  if (rasp_signal_category_equals_encoded(signal, RASP_REPORT_STRING_CATEGORY_MEMORY) ||
      rasp_signal_id_equals_encoded(
          signal, RASP_REPORT_STRING_SIGNAL_INTEGRITY_NATIVE_TEXT_MODIFIED)) {
    if (policy->memory_integrity_enabled == 0U) {
      return 0;
    }
    signal->weight =
        rasp_cap_signal_weight(signal->weight, policy->memory_integrity_weight);
    return 1;
  }

  if (rasp_signal_category_equals_encoded(signal, RASP_REPORT_STRING_CATEGORY_ROOT)) {
    if (policy->root_detection_enabled == 0U) {
      return 0;
    }
    signal->weight =
        rasp_cap_signal_weight(signal->weight, policy->root_detection_weight);
    return 1;
  }

  if (rasp_signal_category_equals_encoded(signal,
                                          RASP_REPORT_STRING_CATEGORY_EMULATOR)) {
    if (policy->emulator_detection_enabled == 0U) {
      return 0;
    }
    signal->weight =
        rasp_cap_signal_weight(signal->weight, policy->emulator_detection_weight);
    return 1;
  }

  return 1;
}

static void rasp_apply_runtime_detector_policy(
    RaspSecurityReport *report, const RaspSecurityPolicy *policy) {
  uint32_t write_index = 0U;

  if (report == NULL || policy == NULL) {
    return;
  }

  for (uint32_t read_index = 0U; read_index < report->signal_count;
       read_index++) {
    RaspSecuritySignal signal = report->signals[read_index];
    if (!rasp_apply_runtime_detector_policy_to_signal(&signal, policy)) {
      continue;
    }
    report->signals[write_index] = signal;
    write_index++;
  }

  report->signal_count = write_index;
  rasp_recalculate_risk_score(report);
}

static int rasp_path_exists(const char *path) {
  return path != NULL && access(path, F_OK) == 0;
}

static void rasp_scan_first_existing_path(const RaspReportStringId *paths,
                                          size_t path_count,
                                          RaspSecurityReport *report,
                                          RaspReportStringId signal_id,
                                          RaspReportStringId category,
                                          uint8_t confidence,
                                          uint8_t severity,
                                          uint8_t weight) {
  for (size_t index = 0U; index < path_count; index++) {
    char path_buffer[PATH_MAX];
    if (!rasp_decode_report_string(paths[index], path_buffer,
                                   sizeof(path_buffer))) {
      continue;
    }
    if (rasp_path_exists(path_buffer)) {
      rasp_report_add_encoded_signal(report, signal_id, category, confidence,
                                     severity, weight, path_buffer);
      return;
    }
  }
}

