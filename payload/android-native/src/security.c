static int rasp_security_collect_with_policy(
    RaspSecurityReport *report, const RaspSecurityPolicy *policy) {
  RaspSecurityPolicy default_policy;
  const RaspSecurityPolicy *effective_policy;
  char path[RASP_DECODED_LONG_STRING_SIZE];

  if (report == NULL) {
    return -1;
  }

  default_policy = rasp_security_default_policy();
  effective_policy = rasp_policy_is_valid(policy) ? policy : &default_policy;

  rasp_report_init(report);
  rasp_harden_process(report);
  if (rasp_decode_report_string(RASP_REPORT_STRING_PATH_PROC_SELF_MAPS, path,
                                sizeof(path))) {
    rasp_scan_maps_path(path, report);
    rasp_scan_self_text_integrity_path(path, report);
  }
  if (rasp_decode_report_string(RASP_REPORT_STRING_PATH_PROC_SELF_STATUS, path,
                                sizeof(path))) {
    rasp_scan_status_path(path, report);
  }
  if (rasp_decode_report_string(RASP_REPORT_STRING_PATH_PROC_SELF_TASK, path,
                                sizeof(path))) {
    rasp_scan_task_threads(path, report);
  }
  if (rasp_decode_report_string(RASP_REPORT_STRING_PATH_PROC_SELF_FD, path,
                                sizeof(path))) {
    rasp_scan_fd_links(path, report);
  }
  if (rasp_decode_report_string(RASP_REPORT_STRING_PATH_PROC_NET_TCP, path,
                                sizeof(path))) {
    rasp_scan_tcp_path(path, report, &g_proc_net_tcp_restricted);
  }
  if (rasp_decode_report_string(RASP_REPORT_STRING_PATH_PROC_NET_TCP6, path,
                                sizeof(path))) {
    rasp_scan_tcp_path(path, report, &g_proc_net_tcp6_restricted);
  }
  if (rasp_decode_report_string(RASP_REPORT_STRING_PATH_PROC_NET_UNIX, path,
                                sizeof(path))) {
    rasp_scan_unix_path(path, report, &g_proc_net_unix_restricted);
  }
  if (rasp_decode_report_string(RASP_REPORT_STRING_PATH_PROC_SELF_ENVIRON, path,
                                sizeof(path))) {
    rasp_scan_environment_path(path, report);
  }
  if (effective_policy->root_detection_enabled != 0U) {
    rasp_scan_root_state(report, effective_policy->root_detection_weight);
  }
  if (effective_policy->emulator_detection_enabled != 0U) {
    rasp_scan_emulator_state(report, effective_policy->emulator_detection_weight);
  }
  rasp_apply_runtime_detector_policy(report, effective_policy);
  (void)rasp_security_apply_policy(report, effective_policy);

  return 0;
}

int rasp_security_collect(RaspSecurityReport *report) {
  return rasp_security_collect_with_policy(report, NULL);
}

