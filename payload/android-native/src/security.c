static uint8_t rasp_rotl8(uint8_t value, unsigned int shift) {
  return (uint8_t)((uint8_t)(value << shift) |
                   (uint8_t)(value >> (8U - shift)));
}

static uint8_t rasp_string_mask(uint8_t key, size_t index, size_t length) {
  const uint8_t position = (uint8_t)(index + 1U);
  const uint8_t span = (uint8_t)length;
  const uint8_t mix =
      (uint8_t)(0x9dU + (uint8_t)(position * 0x3dU) +
                (uint8_t)(span * 0x11U));
  return (uint8_t)(key ^ mix ^ rasp_rotl8(position, 3U));
}

static int rasp_decode_xor_bytes(const uint8_t *encoded_bytes,
                                 size_t encoded_length, char *buffer,
                                 size_t buffer_size) {
  if (encoded_bytes == NULL || buffer == NULL || buffer_size == 0U ||
      encoded_length >= buffer_size) {
    if (buffer != NULL && buffer_size > 0U) {
      buffer[0] = '\0';
    }
    return 0;
  }
  if (!rasp_opaque_true(0x51f00d00U ^ (uint32_t)encoded_length)) {
    buffer[0] = '\0';
    return 0;
  }

  const uint8_t xor_key = rasp_detector_token_xor_key();
  for (size_t index = 0U; index < encoded_length; index++) {
    uint8_t mask = rasp_string_mask(xor_key, index, encoded_length);
    if (rasp_opaque_false(0x7a1b0000U ^ (uint32_t)index)) {
      mask ^= (uint8_t)(encoded_length + index);
    }
    buffer[index] = (char)(encoded_bytes[index] ^ mask);
  }
  buffer[encoded_length] = '\0';
  return 1;
}

